"""Торговый бот для часовых рынков Polymarket "<Монета> Up or Down".

Монета выбирается одной строкой в `config.py` (`COIN = "btc"` или `"eth"`): от неё
зависят пара Binance, слаг рынка, проверка правила резолва и комплект с моделью.
Один процесс — одна монета; чтобы торговать обе, нужны два развёртывания со
своими каталогами (у каждого свои `data/bot.db` и `logs/`) и своим TG-токеном.

Модель и её проверка — в `research/` (см. research/REPORT.md). Здесь только боевая
обвязка: получить данные, посчитать прогноз, выставить лимитку, дождаться исполнения,
записать результат.

Устройство цикла одного часа (время UTC, рынок = свеча H:00:00–H:59:59):

    H−2мин   признаки по свече H−1, обрезанной на 2 минуты → прогноз → лимитный ордер
    H:00     рынок стартовал, ордер уже в стакане
    H:59:59  рынок резолвится по правилу close >= open
    H+1:01   забираем исход, считаем P&L, пишем в БД, шлём в Telegram

Главный инвариант: **ничего новее момента решения в признаки попасть не может**.
Модель обучена ровно на таком входе; любое подглядывание сделает боевой результат
не тем, что показала проверка.
"""

