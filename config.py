def _env(*names: str, default: str = "") -> str:
    """Первое непустое значение из перечисленных переменных окружения.

    Имена POLY_*/TG_* — основные (совпадают с другими проектами, чтобы один .env
    подходил везде); POLYMARKET_*/TELEGRAM_* оставлены как запасные.
    """
    for n in names:
        v = os.getenv(n)
        if v:
            return v.strip()
    return default


