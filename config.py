# --- комиссии ------------------------------------------------------------
#: Комиссия тейкера реальна (help.polymarket.com, раздел Trading Fees, сверено
#: 11.09.2026). Категория Crypto: платит только тейкер, мейкеру ничего не
#: списывают, и ему же идёт часть собранного как ребейт.
#:     fee = shares · FEE_RATE · p · (1−p)          с тейкера
#:     rebate = MAKER_REBATE_SHARE · fee            мейкеру, доля от собранного
#: Максимум — 1.75¢ за шейр у p = 0.50, гаснет к краям. На ставке в 5 шейров это
