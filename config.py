#: ставку по крипте снизили с 0.072 до текущих 0.07.
#:
#: Снятое ложное убеждение (держалось до 11.09.2026): в архиве ленты 27.07–
#: 06.09.2026 поле комиссии равно нулю во всех 596 259 сделках. Раньше это
#: читалось как «комиссии не было». Неверно: поле комиссии в публичной ленте
#: сделок Polymarket просто не заполняется, это не значит, что биржа её не
#: списывала. Формула остаётся консервативной оценкой во всех расчётах
#: (`fee_usd`, P&L); что биржа списала по факту — отдельно, по каждому
#: исполнению, в `fee_charged_usd` (сверить с `usdcSize` из Data API на первых
#: боевых сделках, пока не сделано). С комиссией по формуле новая схема
#: исполнения всё равно даёт положительный результат: +0.0285 на шейр в час
#: вместо +0.0359 без неё (726 часов реплея; подробности —
#: reports/execution_maker_cross.md).
FEE_RATE = 0.07
MAKER_REBATE_SHARE = 0.20

# --- исполнение ----------------------------------------------------------
#: Как ставим заявку. Замер: 747 часовых рынков BTC, 27.07–06.09.2026, настоящий
#: стакан (557 756 снимков, 5 уровней с объёмами) и лента (596 259 сделок),
#: исполнение по очереди — заявка встаёт за уже стоящим объёмом и исполняется,
#: когда встречный объём превысит очередь плюс наш размер.
#:
#: Старая схема (0.49, post-only, GTD до конца часа) исполнялась в 87.7% часов,
#: но точность на исполненных — 50.38% против 56.22% на всей выборке: заявку
#: наливали в основном тогда, когда цена шла против позиции. Ожидание +0.0143 на
#: шейр в час. Новая схема: +0.0470, прирост +0.0327 (t = 5.32, p = 1.3e-7).
#: Из чего он складывается: цена 0.51 вместо 0.49 даёт +0.0171 (t = 3.87), отказ
#: от post-only +0.0081 (t = 2.80), добор тейкером на 12-й минуте +0.0075.
#:
#: Замер сделан ТОЛЬКО на BTC: монитор стакана пишет один рынок. Для ETH схема
#: перенесена по аналогии и отдельно не проверена.

#: Цена лимитной заявки. Замер: 0.51 — максимум, 0.52 равнозначно, 0.50 хуже на
#: 0.008 в час, 0.49 (прежняя) — на 0.016.
LIMIT_PRICE = 0.51

