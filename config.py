# --- комиссии ------------------------------------------------------------
#: Категория Crypto: комиссию платит только тейкер, мейкеру часть возвращается.
#:     fee = shares · FEE_RATE · p · (1−p)          с тейкера
#:     rebate = MAKER_REBATE_SHARE · fee            мейкеру
#: При цене 0.50 это 1.75¢ за шейр против +0.35¢ — на ставке в 5 шейров разница
